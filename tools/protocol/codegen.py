#!/usr/bin/env python3
"""
Firestarter binary command frame codegen.

Reads tools/protocol/command_frame.toml and emits one of four outputs:

  --language cpp            -> command_frame.h       (firmware layout and limits)
  --language python         -> command_frame.py      (host layout and limits)
  --language cpp-vectors    -> command_vectors.h     (firmware native-test vectors)
  --language json-vectors   -> command_vectors.json  (host test vectors)

The vector bytes come from the small reference encoder in this file, so the
host encoder and the firmware decoder are both checked against bytes that
neither of them produced.

Determinism: two runs against the same TOML produce byte-identical output
(no timestamps, sorted iteration, LF line endings).

Stdlib only (Python 3.11+ for tomllib).
"""

import argparse
import json
import struct
import sys
import tomllib
from pathlib import Path

TYPE_FMT = {"u8": "B", "u16": "H", "u32": "I"}
TYPE_SIZE = {"u8": 1, "u16": 2, "u32": 4}
KINDS = ("none", "memory", "config")
RETIRED_COMMANDS = (4, 6)
BANNER = "GENERATED by tools/protocol/codegen.py from tools/protocol/command_frame.toml. Do not edit."


class SpecError(Exception):
    pass


# ===========================================================================
# Loading and validation
# ===========================================================================


def _field_size(field: dict) -> int:
    return TYPE_SIZE[field["type"]] * field.get("count", 1)


def _with_offsets(fields: list) -> list:
    offset = 0
    out = []
    for f in fields:
        out.append({**f, "offset": offset, "size": _field_size(f)})
        offset += _field_size(f)
    return out


def load(path: Path) -> dict:
    with path.open("rb") as fh:
        spec = tomllib.load(fh)

    frame = spec["frame"]
    if frame["header_size"] != 7:
        raise SpecError("header_size must be 7: magic, version, cmd, flags u16, length u16")
    if frame["magic"] < 0x80:
        raise SpecError("magic must be >= 0x80 so JSON-era firmware rejects it")

    for table in ("memory", "config"):
        names = [f["name"] for f in spec[table]]
        if len(names) != len(set(names)):
            raise SpecError(f"duplicate field name in [[{table}]]")
        for f in spec[table]:
            if f["type"] not in TYPE_FMT:
                raise SpecError(f"{table}.{f['name']}: unknown type {f['type']}")
        spec[table] = _with_offsets(spec[table])

    lines = [f for f in spec["memory"] if f["name"] == "address_lines"]
    if not lines or lines[0].get("count") != spec["limits"]["address_lines"]:
        raise SpecError("address_lines.count must equal limits.address_lines")

    bits = [f["present_bit"] for f in spec["config"] if "present_bit" in f]
    if len(bits) != len(set(bits)) or any(b & (b - 1) for b in bits):
        raise SpecError("config present_bit values must be distinct single bits")
    if spec["config"][0]["name"] != "present":
        raise SpecError("the first config field must be `present`")

    seen: dict = {}
    for kind in KINDS:
        for cmd in spec["commands"][kind]:
            if cmd in RETIRED_COMMANDS:
                raise SpecError(f"command {cmd} is retired and must not be listed")
            if cmd in seen:
                raise SpecError(f"command {cmd} listed under both {seen[cmd]} and {kind}")
            seen[cmd] = kind

    codes = [r["code"] for r in spec["refusals"]]
    names = [r["name"] for r in spec["refusals"]]
    if len(codes) != len(set(codes)) or len(names) != len(set(names)) or 0 in codes:
        raise SpecError("refusal codes and names must be unique and non-zero")

    return spec


def payload_kind(spec: dict, cmd: int) -> str:
    for kind in KINDS:
        if cmd in spec["commands"][kind]:
            return kind
    return "none"


def payload_size(spec: dict, kind: str) -> int:
    if kind == "none":
        return 0
    return sum(f["size"] for f in spec[kind])


# ===========================================================================
# Reference encoder (vectors only)
# ===========================================================================


def _pack(field: dict, value) -> bytes:
    fmt = ">" + TYPE_FMT[field["type"]]
    if field.get("count"):
        values = list(value) + [0xFF] * (field["count"] - len(value))
        if len(values) != field["count"]:
            raise SpecError(f"{field['name']}: more than {field['count']} values")
        return b"".join(struct.pack(fmt, v) for v in values)
    return struct.pack(fmt, value)


def _memory_values(spec: dict, fields: dict) -> dict:
    bus_config = fields.get("bus-config", {})
    values = {}
    for f in spec["memory"]:
        source = bus_config if f.get("bus_config") else fields
        if f["name"] == "address_lines":
            values[f["name"]] = source.get(f["key"], [])
        elif f["name"] in ("rw_line", "vpp_line"):
            values[f["name"]] = source.get(f["key"], spec["limits"]["line_absent"])
        elif f["name"] == "static_high_mask":
            values[f["name"]] = sum(1 << line for line in source.get(f["key"], []))
        else:
            values[f["name"]] = source.get(f["key"], 0)
    return values


def _config_values(spec: dict, fields: dict) -> dict:
    values = {"present": 0}
    for f in spec["config"][1:]:
        if f["key"] in fields:
            values["present"] |= f["present_bit"]
            values[f["name"]] = fields[f["key"]]
        else:
            values[f["name"]] = 0
    return values


def _default_values(spec: dict, kind: str) -> dict:
    if kind == "memory":
        return _memory_values(spec, {})
    if kind == "config":
        return _config_values(spec, {})
    return {}


def encode_values(spec: dict, cmd: int, flags: int, values: dict) -> bytes:
    kind = payload_kind(spec, cmd)
    payload = b"".join(_pack(f, values[f["name"]]) for f in spec[kind]) if kind != "none" else b""
    header = struct.pack(">BBBHH", spec["frame"]["magic"], spec["frame"]["version"], cmd, flags, len(payload))
    return header + payload


def accepted_vectors(spec: dict) -> list:
    out = []
    for v in spec["vectors"]:
        kind = payload_kind(spec, v["cmd"])
        if kind == "memory":
            values = _memory_values(spec, v["fields"])
        elif kind == "config":
            values = _config_values(spec, v["fields"])
        else:
            if v["fields"]:
                raise SpecError(f"vector {v['name']}: command {v['cmd']} carries no payload")
            values = {}
        frame = encode_values(spec, v["cmd"], v["flags"], values)
        out.append({**v, "kind": kind, "values": values, "frame": frame})
    return out


def refused_vectors(spec: dict) -> list:
    refusal_codes = {r["name"]: r["code"] for r in spec["refusals"]}
    out = []
    for v in spec["refused_vectors"]:
        if "frame" in v:
            frame = bytes.fromhex(v["frame"])
        else:
            kind = payload_kind(spec, v["cmd"])
            values = {**_default_values(spec, kind), **v["raw"]}
            frame = encode_values(spec, v["cmd"], v.get("flags", 0), values)
        if v.get("reason") == "frame":
            code = 0
        else:
            code = refusal_codes[v["refusal"]]
        out.append({"name": v["name"], "frame": frame, "code": code})
    return out


# ===========================================================================
# Emitters
# ===========================================================================


def _c_name(name: str) -> str:
    return name.upper()


def emit_cpp(spec: dict) -> str:
    frame, limits = spec["frame"], spec["limits"]
    lines = [
        "/*",
        f" * {BANNER}",
        " *",
        " * Binary command frame layout. Every multi-byte field is big-endian.",
        " */",
        "",
        "#ifndef __COMMAND_FRAME_H__",
        "#define __COMMAND_FRAME_H__",
        "",
        "#include <stdint.h>",
        "",
        f"#define CF_MAGIC 0x{frame['magic']:02X}",
        f"#define CF_VERSION {frame['version']}",
        f"#define CF_HEADER_SIZE {frame['header_size']}",
        "#define CF_OFF_MAGIC 0",
        "#define CF_OFF_VERSION 1",
        "#define CF_OFF_CMD 2",
        "#define CF_OFF_FLAGS 3",
        "#define CF_OFF_LENGTH 5",
        "",
        f"#define CF_ADDRESS_LINES {limits['address_lines']}",
        f"#define CF_BUS_LINES {limits['bus_lines']}",
        f"#define CF_LINE_ABSENT 0x{limits['line_absent']:02X}",
        f"#define CF_READ_TIMING_MAX_US {limits['read_timing_max_us']}UL",
        f"#define CF_FLAGS_MASK 0x{limits['flags_mask']:04X}",
        "",
        "#define CF_KIND_NONE 0",
        "#define CF_KIND_MEMORY 1",
        "#define CF_KIND_CONFIG 2",
        "",
    ]
    for kind in ("memory", "config"):
        prefix = f"CF_{kind.upper()}"
        lines.append(f"#define {prefix}_SIZE {payload_size(spec, kind)}")
        for f in spec[kind]:
            lines.append(f"#define {prefix}_OFF_{_c_name(f['name'])} {f['offset']}")
        lines.append("")
    mask = 0
    for f in spec["config"][1:]:
        lines.append(f"#define CF_CONFIG_PRESENT_{_c_name(f['name'])} 0x{f['present_bit']:02X}")
        mask |= f["present_bit"]
    lines.append(f"#define CF_CONFIG_PRESENT_MASK 0x{mask:02X}")
    lines.append("")
    for r in sorted(spec["refusals"], key=lambda r: r["code"]):
        lines.append(f"#define CF_REFUSE_{r['name']} {r['code']}  /* {r['text']} */")
    lines += [
        "",
        "/* The payload a command carries. Unlisted commands carry none. */",
        "static inline uint8_t cf_payload_kind(uint8_t cmd) {",
        "    switch (cmd) {",
    ]
    for kind in ("memory", "config"):
        for cmd in sorted(spec["commands"][kind]):
            lines.append(f"        case {cmd}:")
        lines.append(f"            return CF_KIND_{kind.upper()};")
    lines += [
        "        default:",
        "            return CF_KIND_NONE;",
        "    }",
        "}",
        "",
        "#endif  // __COMMAND_FRAME_H__",
        "",
    ]
    return "\n".join(lines)


def emit_python(spec: dict) -> str:
    frame, limits = spec["frame"], spec["limits"]
    lines = [
        f'"""{BANNER}',
        "",
        "Binary command frame layout. Every multi-byte field is big-endian.",
        '"""',
        "",
        f"MAGIC = 0x{frame['magic']:02X}",
        f"VERSION = {frame['version']}",
        f"HEADER_SIZE = {frame['header_size']}",
        'HEADER_FORMAT = ">BBBHH"',
        "",
        f"ADDRESS_LINES = {limits['address_lines']}",
        f"BUS_LINES = {limits['bus_lines']}",
        f"LINE_ABSENT = 0x{limits['line_absent']:02X}",
        f"READ_TIMING_MAX_US = {limits['read_timing_max_us']}",
        f"FLAGS_MASK = 0x{limits['flags_mask']:04X}",
        "",
        "# (name, command-dict key, struct format, count, inside bus-config)",
        "MEMORY_FIELDS = (",
    ]
    for f in spec["memory"]:
        lines.append(
            f'    ("{f["name"]}", "{f["key"]}", "{TYPE_FMT[f["type"]]}", '
            f'{f.get("count", 1)}, {bool(f.get("bus_config"))}),'
        )
    lines += [")", f"MEMORY_SIZE = {payload_size(spec, 'memory')}", "", "# (name, command-dict key, struct format, present bit)", "CONFIG_FIELDS = ("]
    for f in spec["config"][1:]:
        lines.append(f'    ("{f["name"]}", "{f["key"]}", "{TYPE_FMT[f["type"]]}", 0x{f["present_bit"]:02X}),')
    lines += [")", f"CONFIG_SIZE = {payload_size(spec, 'config')}", "", "PAYLOAD_KIND = {"]
    for kind in ("memory", "config", "none"):
        for cmd in sorted(spec["commands"][kind]):
            lines.append(f'    {cmd}: "{kind}",')
    lines += ["}", "", "# MSG_ERR_BAD_COMMAND parameter -> reason", "REFUSALS = {"]
    for r in sorted(spec["refusals"], key=lambda r: r["code"]):
        lines.append(f'    {r["code"]}: "{r["text"]}",')
    lines += ["}", ""]
    return "\n".join(lines)


def _c_bytes(frame: bytes) -> str:
    return ", ".join(f"0x{b:02X}" for b in frame) if frame else "0x00"


def emit_cpp_vectors(spec: dict) -> str:
    mem = [f["name"] for f in spec["memory"] if f["name"] != "address_lines"]
    cfg = [f["name"] for f in spec["config"]]
    lines = [
        "/*",
        f" * {BANNER}",
        " *",
        " * Golden command frames for the native decoder tests.",
        " */",
        "",
        "#ifndef __COMMAND_VECTORS_H__",
        "#define __COMMAND_VECTORS_H__",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    const char* name;",
        "    const uint8_t* frame;",
        "    uint16_t frame_len;",
        "    uint8_t cmd;",
        "    uint16_t flags;",
        "    uint8_t kind;",
    ]
    lines += [f"    uint32_t {n};" for n in mem]
    lines.append(f"    uint8_t address_lines[{spec['limits']['address_lines']}];")
    lines += [f"    uint32_t cfg_{n};" for n in cfg]
    lines += ["} cf_accept_vector_t;", "", "typedef struct {", "    const char* name;", "    const uint8_t* frame;", "    uint16_t frame_len;", "    uint8_t refusal;  /* 0 = refused as a frame (MSG_ERR_BAD_FRAME) */", "} cf_refuse_vector_t;", ""]

    accepted = accepted_vectors(spec)
    refused = refused_vectors(spec)
    for v in accepted + refused:
        lines.append(f"static const uint8_t cf_frame_{v['name']}[] = {{{_c_bytes(v['frame'])}}};")
    lines += ["", "static const cf_accept_vector_t CF_ACCEPT_VECTORS[] = {"]
    kind_ids = {"none": 0, "memory": 1, "config": 2}
    for v in accepted:
        values = v["values"]
        parts = [f'"{v["name"]}"', f"cf_frame_{v['name']}", str(len(v["frame"])), str(v["cmd"]), f"0x{v['flags']:04X}", str(kind_ids[v["kind"]])]
        parts += [str(values.get(n, 0)) for n in mem]
        lines_list = values.get("address_lines", [])
        padded = list(lines_list) + [0xFF] * (spec["limits"]["address_lines"] - len(lines_list))
        parts.append("{" + ", ".join(str(x) for x in padded) + "}")
        parts += [str(values.get(n, 0)) for n in cfg]
        lines.append("    {" + ", ".join(parts) + "},")
    lines += ["};", "", "static const cf_refuse_vector_t CF_REFUSE_VECTORS[] = {"]
    for v in refused:
        lines.append(f'    {{"{v["name"]}", cf_frame_{v["name"]}, {len(v["frame"])}, {v["code"]}}},')
    lines += [
        "};",
        "",
        "#define CF_ACCEPT_VECTOR_COUNT (sizeof(CF_ACCEPT_VECTORS) / sizeof(CF_ACCEPT_VECTORS[0]))",
        "#define CF_REFUSE_VECTOR_COUNT (sizeof(CF_REFUSE_VECTORS) / sizeof(CF_REFUSE_VECTORS[0]))",
        "",
        "#endif  // __COMMAND_VECTORS_H__",
        "",
    ]
    return "\n".join(lines)


def emit_json_vectors(spec: dict) -> str:
    out = {
        "_generated": BANNER,
        "accept": [
            {"name": v["name"], "cmd": v["cmd"], "flags": v["flags"], "fields": v["fields"], "frame": v["frame"].hex()}
            for v in accepted_vectors(spec)
        ],
        "refuse": [{"name": v["name"], "frame": v["frame"].hex(), "refusal": v["code"]} for v in refused_vectors(spec)],
    }
    return json.dumps(out, indent=2, sort_keys=True) + "\n"


EMITTERS = {
    "cpp": emit_cpp,
    "python": emit_python,
    "cpp-vectors": emit_cpp_vectors,
    "json-vectors": emit_json_vectors,
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--spec", type=Path, default=Path(__file__).with_name("command_frame.toml"))
    parser.add_argument("--language", choices=sorted(EMITTERS))
    parser.add_argument("--target", type=Path)
    parser.add_argument("--check", action="store_true", help="validate the spec and exit")
    args = parser.parse_args()
    try:
        spec = load(args.spec)
        if args.check:
            accepted_vectors(spec)
            refused_vectors(spec)
            print("OK: command_frame.toml is valid.")
            return 0
        if not args.language or not args.target:
            parser.error("--language and --target are required unless --check is given")
        args.target.write_text(EMITTERS[args.language](spec), newline="\n")
    except SpecError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
