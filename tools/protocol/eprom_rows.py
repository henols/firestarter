#!/usr/bin/env python3
"""
Firestarter 27C EPROM write-time rows codegen.

Reads tools/protocol/eprom_rows.toml and emits one of two outputs:

  --language cpp     -> eprom_rows.h   (firmware: eprom_params.cpp, configure_eprom)
  --language python  -> eprom_rows.py  (host: write_budget.py)

Determinism: two runs against the same TOML produce byte-identical output
(no timestamps, sorted iteration, LF line endings).

Stdlib only (Python 3.11+ for tomllib).
"""

import argparse
import sys
import tomllib
from pathlib import Path

BANNER = "GENERATED by tools/protocol/eprom_rows.py from tools/protocol/eprom_rows.toml. Do not edit."
COLUMNS = ("max_pulses", "energy_cap_us", "fallback_pulse_us")
LIMITS = {"max_pulses": 0xFF, "energy_cap_us": 0xFFFFFFFF, "fallback_pulse_us": 0xFFFFFFFF}


class SpecError(Exception):
    pass


def load(path: Path) -> list:
    with path.open("rb") as fh:
        rows = tomllib.load(fh)["rows"]
    protocols = [r["protocol"] for r in rows]
    if len(protocols) != len(set(protocols)):
        raise SpecError("duplicate protocol in [[rows]]")
    for r in rows:
        for col in COLUMNS:
            value = r[col]
            if not isinstance(value, int) or not 0 <= value <= LIMITS[col]:
                raise SpecError(f"row 0x{r['protocol']:02X}: {col} {value!r} is out of range")
        if r["max_pulses"] == 0 or r["fallback_pulse_us"] == 0:
            raise SpecError(f"row 0x{r['protocol']:02X}: max_pulses and fallback_pulse_us must be > 0")
    return sorted(rows, key=lambda r: r["protocol"])


def emit_cpp(rows: list) -> str:
    lines = [
        "/*",
        f" * {BANNER}",
        " *",
        " * The write-time columns of the three 27C EPROM rows. The host computes",
        " * its write timeout from the same values.",
        " */",
        "",
        "#ifndef __EPROM_ROWS_H__",
        "#define __EPROM_ROWS_H__",
        "",
    ]
    for r in rows:
        p = f"EPROM_ROW_{r['protocol']:02X}"
        lines += [
            f"/* 0x{r['protocol']:02X} {r['name']} */",
            f"#define {p}_MAX_PULSES {r['max_pulses']}",
            f"#define {p}_ENERGY_CAP_US {r['energy_cap_us']}UL",
            f"#define {p}_FALLBACK_PULSE_US {r['fallback_pulse_us']}UL",
            "",
        ]
    lines += ["#endif  // __EPROM_ROWS_H__", ""]
    return "\n".join(lines)


def emit_python(rows: list) -> str:
    lines = [
        f'"""{BANNER}',
        "",
        "The write-time columns of the three 27C EPROM rows. The firmware programs",
        "with the same values.",
        '"""',
        "",
        "# protocol: (max_pulses, energy_cap_us, fallback_pulse_us)",
        "EPROM_ROWS = {",
    ]
    for r in rows:
        values = ", ".join(str(r[col]) for col in COLUMNS)
        lines.append(f"    0x{r['protocol']:02X}: ({values}),  # {r['name']}")
    lines += ["}", ""]
    return "\n".join(lines)


EMITTERS = {"cpp": emit_cpp, "python": emit_python}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--spec", type=Path, default=Path(__file__).with_name("eprom_rows.toml"))
    parser.add_argument("--language", choices=sorted(EMITTERS))
    parser.add_argument("--target", type=Path)
    parser.add_argument("--check", action="store_true", help="validate the spec and exit")
    args = parser.parse_args()
    try:
        rows = load(args.spec)
        if args.check:
            print("OK: eprom_rows.toml is valid.")
            return 0
        if not args.language or not args.target:
            parser.error("--language and --target are required unless --check is given")
        args.target.write_text(EMITTERS[args.language](rows), newline="\n")
    except SpecError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
