#!/usr/bin/env python3
"""
Firestarter protocol capability table codegen.

Reads tools/protocol/protocol_caps.toml and emits one of two outputs:

  --language cpp     -> protocol_caps.h   (firmware)
  --language python  -> protocol_caps.py  (host, database generator)

Determinism: two runs against the same TOML produce byte-identical output.

Stdlib only (Python 3.11+ for tomllib).
"""

import argparse
import sys
import tomllib
from pathlib import Path

BANNER = "GENERATED by tools/protocol/protocol_caps.py from tools/protocol/protocol_caps.toml. Do not edit."
VPP_ROUTES = ("none", "oe_vpp", "a9", "pin1")


class SpecError(Exception):
    pass


def load(path: Path) -> list:
    with path.open("rb") as fh:
        rows = tomllib.load(fh)["protocols"]
    ids = [r["protocol"] for r in rows]
    if len(ids) != len(set(ids)):
        raise SpecError("duplicate protocol in [[protocols]]")
    names = [r["name"] for r in rows]
    if len(names) != len(set(names)):
        raise SpecError("duplicate name in [[protocols]]")
    for r in rows:
        tag = f"protocol 0x{r['protocol']:02X}"
        if not isinstance(r["protocol"], int) or not 0 < r["protocol"] <= 0xFF:
            raise SpecError(f"{tag}: protocol must be 1..0xFF")
        if r["vpp_route"] not in VPP_ROUTES:
            raise SpecError(f"{tag}: vpp_route {r['vpp_route']!r} is not one of {VPP_ROUTES}")
        if not r["command_set"]:
            raise SpecError(f"{tag}: command_set must not be empty")
    return sorted(rows, key=lambda r: r["protocol"])


def emit_cpp(rows: list) -> str:
    lines = [
        "/*",
        f" * {BANNER}",
        " *",
        " * The protocols the firmware has a handler for, and where each routes VPP.",
        " */",
        "",
        "#ifndef __PROTOCOL_CAPS_H__",
        "#define __PROTOCOL_CAPS_H__",
        "",
    ]
    for r in rows:
        p = f"PROTOCOL_CAPS_{r['protocol']:02X}"
        lines += [
            f"/* 0x{r['protocol']:02X} {r['name']}: {r['command_set']} */",
            f"#define {p}_VPP_ROUTE_{r['vpp_route'].upper()} 1",
            "",
        ]
    lines += ["#endif  // __PROTOCOL_CAPS_H__", ""]
    return "\n".join(lines)


def emit_python(rows: list) -> str:
    lines = [
        f'"""{BANNER}',
        "",
        "The protocols the firmware has a handler for, and where each routes VPP.",
        '"""',
        "",
        "# protocol: (name, command_set, vpp_route)",
        "PROTOCOL_CAPS = {",
    ]
    for r in rows:
        lines.append(f"    0x{r['protocol']:02X}: ({r['name']!r}, {r['command_set']!r}, {r['vpp_route']!r}),")
    lines += ["}", ""]
    return "\n".join(lines)


EMITTERS = {"cpp": emit_cpp, "python": emit_python}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--spec", type=Path, default=Path(__file__).with_name("protocol_caps.toml"))
    parser.add_argument("--language", choices=sorted(EMITTERS))
    parser.add_argument("--target", type=Path)
    parser.add_argument("--check", action="store_true", help="validate the spec and exit")
    args = parser.parse_args()
    try:
        rows = load(args.spec)
        if args.check:
            print("OK: protocol_caps.toml is valid.")
            return 0
        if not args.language or not args.target:
            parser.error("--language and --target are required unless --check is given")
        args.target.write_text(EMITTERS[args.language](rows), newline="\n")
    except SpecError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
